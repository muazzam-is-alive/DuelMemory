/**
 * Creates a guaranteed high-definition SVG Data URI vector illustration for any card pair
 */
export const createSvgCardIllustration = (
  pairId: string,
  symbol: string,
  name: string,
  colorGradient: string = 'from-amber-400 to-orange-500'
): string => {
  let color1 = '#f59e0b';
  let color2 = '#ea580c';

  if (colorGradient.includes('pink') || colorGradient.includes('rose')) {
    color1 = '#ec4899';
    color2 = '#e11d48';
  } else if (colorGradient.includes('blue') || colorGradient.includes('sky')) {
    color1 = '#3b82f6';
    color2 = '#1d4ed8';
  } else if (colorGradient.includes('emerald') || colorGradient.includes('teal')) {
    color1 = '#10b981';
    color2 = '#0f766e';
  } else if (colorGradient.includes('purple') || colorGradient.includes('indigo')) {
    color1 = '#8b5cf6';
    color2 = '#4338ca';
  } else if (colorGradient.includes('cyan')) {
    color1 = '#06b6d4';
    color2 = '#0e7490';
  } else if (colorGradient.includes('yellow') || colorGradient.includes('amber')) {
    color1 = '#f59e0b';
    color2 = '#b45309';
  } else if (colorGradient.includes('red')) {
    color1 = '#ef4444';
    color2 = '#b91c1c';
  } else if (colorGradient.includes('lime') || colorGradient.includes('green')) {
    color1 = '#84cc16';
    color2 = '#15803d';
  }

  // Safe XML escaping for card name and symbol
  const safeName = name.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').toUpperCase();
  const safeSymbol = symbol.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="400" height="400" viewBox="0 0 400 400">
    <defs>
      <linearGradient id="bg_${pairId}" x1="0%" y1="0%" x2="100%" y2="100%">
        <stop offset="0%" stop-color="${color1}"/>
        <stop offset="100%" stop-color="${color2}"/>
      </linearGradient>
      <radialGradient id="glow_${pairId}" cx="50%" cy="40%" r="55%">
        <stop offset="0%" stop-color="#ffffff" stop-opacity="0.45"/>
        <stop offset="100%" stop-color="#ffffff" stop-opacity="0"/>
      </radialGradient>
      <filter id="sh_${pairId}" x="-20%" y="-20%" width="140%" height="140%">
        <feDropShadow dx="0" dy="6" stdDeviation="5" flood-color="#000000" flood-opacity="0.3"/>
      </filter>
    </defs>
    <rect width="400" height="400" rx="36" fill="url(#bg_${pairId})"/>
    <circle cx="200" cy="175" r="140" fill="url(#glow_${pairId})"/>
    <circle cx="200" cy="175" r="110" fill="#ffffff" fill-opacity="0.18" stroke="#ffffff" stroke-width="4" stroke-dasharray="14 10"/>
    <text x="200" y="195" font-size="110" text-anchor="middle" dominant-baseline="middle" filter="url(#sh_${pairId})">${safeSymbol}</text>
    <rect x="36" y="315" width="328" height="58" rx="20" fill="#ffffff" fill-opacity="0.95" filter="url(#sh_${pairId})"/>
    <text x="200" y="352" font-size="22" font-family="system-ui, -apple-system, sans-serif" font-weight="900" fill="#0f172a" text-anchor="middle" letter-spacing="1">${safeName}</text>
  </svg>`;

  return `data:image/svg+xml;charset=utf-8,${encodeURIComponent(svg)}`;
};

/**
 * Returns a high quality illustration URL for a pair
 */
export const getIllustrationUrl = (
  pairId: string,
  fallbackSymbol: string = '✨',
  name: string = 'Card',
  colorGradient: string = 'from-amber-400 to-orange-500'
): string => {
  return createSvgCardIllustration(pairId, fallbackSymbol, name, colorGradient);
};

